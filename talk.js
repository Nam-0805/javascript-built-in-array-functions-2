// โจทย์ : เรามี Array [ 9,1,2,3,4,5,6 ] และเราต้องทำอย่างไร 
// - ถ้าอยากให้เลขใน Array นี้มีเฉพาะเลขคู่
// - หากเลขไหนที่เป็นเลขคี่ใน Array ให้ทำการเปลี่ยนเลขคี่เป็นเลขคู่
// คำตอบที่ควรจะเป็น : [10,2,2,4,4,6,6] หรือ [8,0,2,2,4,4,6]
//เอาเลขคู่ออก เอาเลขคี่ออกมา แล้วเปลี่ยนเป็นเลขคู่
let numbers = [ 9,1,2,3,4,5,6 ];

function onlyEvenNumber () { //ไม่ใส่อะไรก็ได้เหมือนกัน เพราะจะส่งอะไรเข้ามาก็ได้

    return numbers.map((num)=> num % 2 !== 0 ? num + 1 : num);
    
}

let result = onlyEvenNumber(numbers); //
console.log(result);